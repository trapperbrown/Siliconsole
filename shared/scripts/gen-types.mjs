const defines = {
  SC_APP_NAME: cfg.appName,
  SC_SERVICE_NAME: cfg.service.name,
  SC_SERVICE_DISPLAY: cfg.service.displayName,
  SC_SERVICE_DESCRIPTION: cfg.service.description,
  SC_SERVICE_SUBFOLDER: cfg.service.installSubfolder,
  SC_SERVICE_EXE: cfg.service.exeName,
  SC_SERVICE_RESTART_MS: String(cfg.service.recoveryRestartDelayMs),
  SC_PAWNIO_SERVICE: cfg.pawnio.serviceName,
  SC_PAWNIO_URL: cfg.pawnio.setupUrl,
  SC_PAWNIO_SIGNER: cfg.pawnio.setupSigner,
};
