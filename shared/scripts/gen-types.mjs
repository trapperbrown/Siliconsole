// Generates TypeScript, C#, and Rust types from shared/schemas/*.schema.json.
// Supports the schema subset used in this repo: object, array, enum, const, oneOf of $ref,
// nullable via ["T", "null"], string-keyed maps via additionalProperties, and local $ref.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const schemaDir = join(root, "shared", "schemas");
const out = {
  ts: join(root, "desktop", "src", "generated", "schema-types.ts"),
  cs: join(root, "sensor-service", "src", "Generated", "SchemaTypes.cs"),
  rs: join(root, "desktop", "src-tauri", "src", "generated.rs"),
};

const defs = new Map(); // name -> schema
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort()) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf8"));
  for (const [name, def] of Object.entries(schema.$defs ?? {})) {
    if (defs.has(name)) throw new Error(`Duplicate $defs name "${name}" in ${file}`);
    defs.set(name, def);
  }
}

const refName = (ref) => ref.split("/").pop();
const pascal = (s) => s[0].toUpperCase() + s.slice(1);
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
const RUST_KEYWORDS = new Set(["type", "match", "ref", "move", "fn", "struct", "enum", "mod", "use", "impl"]);

const isStruct = (d) => d.type === "object" && d.properties;
const isMap = (d) => d.type === "object" && !d.properties && typeof d.additionalProperties === "object";
const isAlias = (d) => !isStruct(d) && !d.oneOf; // enum or primitive alias

function nullable(schema) {
  return Array.isArray(schema.type) && schema.type.includes("null");
}
function baseType(schema) {
  return Array.isArray(schema.type) ? schema.type.find((t) => t !== "null") : schema.type;
}

// Inline object properties get hoisted to named structs: Parent + Prop.
const inlineStructs = [];
function hoist(parent, prop, schema) {
  const name = parent + pascal(prop);
  inlineStructs.push([name, schema]);
  return { $ref: `#/$defs/${name}` };
}
for (const [name, def] of [...defs]) {
  if (!isStruct(def)) continue;
  for (const [prop, ps] of Object.entries(def.properties)) {
    if (isStruct(ps)) def.properties[prop] = hoist(name, prop, ps);
  }
}
for (const [n, s] of inlineStructs) defs.set(n, s);

// ---------- TypeScript ----------
function tsType(s) {
  let t;
  if (s.$ref) t = refName(s.$ref);
  else if ("const" in s) t = JSON.stringify(s.const);
  else if (s.enum) t = s.enum.map((v) => JSON.stringify(v)).join(" | ");
  else if (s.oneOf) t = s.oneOf.map(tsType).join(" | ");
  else {
    const b = baseType(s);
    if (b === "integer" || b === "number") t = "number";
    else if (b === "string") t = "string";
    else if (b === "boolean") t = "boolean";
    else if (b === "array") t = `${wrapTs(tsType(s.items))}[]`;
    else if (isMap(s)) t = `Record<string, ${tsType(s.additionalProperties)}>`;
    else t = "unknown";
  }
  return nullable(s) ? `${t} | null` : t;
}
const wrapTs = (t) => (t.includes("|") ? `(${t})` : t);

function genTs() {
  const lines = ["// Generated by shared/scripts/gen-types.mjs. Do not edit by hand.", ""];
  for (const [name, d] of defs) {
    if (d.description) lines.push(`/** ${d.description} */`);
    if (isStruct(d)) {
      const req = new Set(d.required ?? []);
      lines.push(`export interface ${name} {`);
      for (const [p, ps] of Object.entries(d.properties)) {
        if (p.startsWith("$")) continue;
        lines.push(`  ${p}${req.has(p) ? "" : "?"}: ${tsType(ps)};`);
      }
      lines.push("}", "");
    } else {
      lines.push(`export type ${name} = ${tsType(d)};`, "");
    }
  }
  return lines.join("\n");
}

// ---------- C# ----------
function resolveAlias(s) {
  while (s.$ref && isAlias(defs.get(refName(s.$ref)))) {
    const target = defs.get(refName(s.$ref));
    s = { ...target, type: nullable(s) ? [baseType(target) ?? "string", "null"] : target.type ?? "string" };
  }
  return s;
}
function csType(s) {
  s = resolveAlias(s);
  let t;
  if (s.$ref) t = refName(s.$ref);
  else if ("const" in s) t = "string";
  else if (s.enum) t = "string";
  else {
    const b = baseType(s);
    if (b === "integer") t = s.format === "int64" ? "long" : "int";
    else if (b === "number") t = "double";
    else if (b === "string") t = "string";
    else if (b === "boolean") t = "bool";
    else if (b === "array") t = `IReadOnlyList<${csType(s.items)}>`;
    else if (isMap(s)) t = `IReadOnlyDictionary<string, ${csType(s.additionalProperties)}>`;
    else t = "System.Text.Json.JsonElement";
  }
  return nullable(s) ? `${t}?` : t;
}

function genCs() {
  const lines = [
    "// Generated by shared/scripts/gen-types.mjs. Do not edit by hand.",
    "#nullable enable",
    "using System.Collections.Generic;",
    "",
    "namespace Siliconsole.SensorService.Generated;",
    "",
  ];
  for (const [name, d] of defs) {
    if (!isStruct(d)) continue;
    const req = new Set(d.required ?? []);
    lines.push(`public sealed record ${name}`, "{");
    for (const [p, ps] of Object.entries(d.properties)) {
      if (p.startsWith("$")) continue;
      const prop = pascal(p);
      if ("const" in ps) {
        lines.push(`    public string ${prop} { get; init; } = ${JSON.stringify(ps.const)};`);
      } else if (req.has(p)) {
        lines.push(`    public required ${csType(ps)} ${prop} { get; init; }`);
      } else {
        const t = csType(ps);
        lines.push(`    public ${t.endsWith("?") ? t : t + "?"} ${prop} { get; init; }`);
      }
    }
    lines.push("}", "");
  }
  return lines.join("\n");
}

// ---------- Rust ----------
function rsType(s) {
  s = resolveAlias(s);
  let t;
  if (s.$ref) t = refName(s.$ref);
  else if ("const" in s || s.enum) t = "String";
  else {
    const b = baseType(s);
    if (b === "integer") t = "i64";
    else if (b === "number") t = "f64";
    else if (b === "string") t = "String";
    else if (b === "boolean") t = "bool";
    else if (b === "array") t = `Vec<${rsType(s.items)}>`;
    else if (isMap(s)) t = `std::collections::BTreeMap<String, ${rsType(s.additionalProperties)}>`;
    else t = "serde_json::Value";
  }
  return nullable(s) ? `Option<${t}>` : t;
}

function genRs() {
  const lines = [
    "// Generated by shared/scripts/gen-types.mjs. Do not edit by hand.",
    "#![allow(dead_code)]",
    "use serde::{Deserialize, Serialize};",
    "",
  ];
  for (const [name, d] of defs) {
    if (!isStruct(d)) continue;
    const req = new Set(d.required ?? []);
    lines.push("#[derive(Debug, Clone, Default, Serialize, Deserialize)]", '#[serde(rename_all = "camelCase")]', `pub struct ${name} {`);
    for (const [p, ps] of Object.entries(d.properties)) {
      if (p.startsWith("$")) continue;
      let field = snake(p);
      if (RUST_KEYWORDS.has(field)) field = `r#${field}`;
      let t = rsType(ps);
      if (!req.has(p)) {
        if (!t.startsWith("Option<")) t = `Option<${t}>`;
        lines.push('    #[serde(default, skip_serializing_if = "Option::is_none")]');
      } else if (t.startsWith("Option<")) {
        lines.push("    #[serde(default)]");
      }
      lines.push(`    pub ${field}: ${t},`);
    }
    lines.push("}", "");
  }
  return lines.join("\n");
}

for (const [key, text] of [["ts", genTs()], ["cs", genCs()], ["rs", genRs()]]) {
  mkdirSync(dirname(out[key]), { recursive: true });
  writeFileSync(out[key], text.replace(/\n+$/, "\n"));
  console.log(`wrote ${out[key]}`);
}

// Keep tauri.conf.json in step with the central config, so a rename stays a one-line change.
const cfg = JSON.parse(readFileSync(join(root, "shared", "config", "defaults.json"), "utf8"));
const tauriPath = join(root, "desktop", "src-tauri", "tauri.conf.json");
const tauri = JSON.parse(readFileSync(tauriPath, "utf8"));
tauri.productName = cfg.appName;
tauri.mainBinaryName = cfg.appName;
tauri.identifier = cfg.appId;
tauri.build.devUrl = `http://localhost:${cfg.devServer.port}`;
const main = tauri.app.windows.find((w) => w.label === "main");
Object.assign(main, { title: cfg.appName, width: cfg.window.width, height: cfg.window.height, minWidth: cfg.window.minWidth, minHeight: cfg.window.minHeight });
const overlay = tauri.app.windows.find((w) => w.label === "overlay");
Object.assign(overlay, { title: `${cfg.appName} Overlay`, width: cfg.overlay.widthPx, height: cfg.overlay.heightPx });
tauri.bundle.publisher = cfg.appName;
tauri.bundle.copyright = `${cfg.appName} contributors`;
tauri.bundle.resources = {
  [`../../sensor-service/publish/${cfg.service.exeName}`]: `${cfg.service.installSubfolder}/${cfg.service.exeName}`,
  "../../sensor-service/publish/defaults.json": `${cfg.service.installSubfolder}/defaults.json`,
  "../../THIRD_PARTY_NOTICES.md": "THIRD_PARTY_NOTICES.md",
};
writeFileSync(tauriPath, JSON.stringify(tauri, null, 2) + "\n");
console.log(`synced ${tauriPath}`);

