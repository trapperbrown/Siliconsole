// Writes THIRD_PARTY_NOTICES.md from the real dependency graphs: NuGet (sensor service runtime),
// Cargo (Tauri core, Windows target) and pnpm (frontend production deps). Run after restoring/building.
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const cfg = JSON.parse(readFileSync(join(root, "shared/config/defaults.json"), "utf8"));
const rows = (list) => list.map((d) => `| ${d.name} | ${d.version} | ${d.license || "see package"} |`).join("\n");
const table = (list) => `| Package | Version | License |\n| --- | --- | --- |\n${rows(list)}`;

// ---------- NuGet ----------
const assets = JSON.parse(readFileSync(join(root, "sensor-service/src/obj/project.assets.json"), "utf8"));
const nuget = Object.entries(assets.libraries)
  .filter(([, v]) => v.type === "package")
  .map(([key]) => {
    const [name, version] = key.split("/");
    const nuspec = join(homedir(), ".nuget/packages", name.toLowerCase(), version, `${name.toLowerCase()}.nuspec`);
    let license = "";
    if (existsSync(nuspec)) {
      const x = readFileSync(nuspec, "utf8");
      // Some packages ship the license as a file; recognize the common ones from their text.
      const file = x.match(/<license type="file">([^<]+)<\/license>/)?.[1];
      const text = file && existsSync(join(dirname(nuspec), file)) ? readFileSync(join(dirname(nuspec), file), "utf8") : "";
      const fromFile = /Apache License/.test(text) ? "Apache-2.0" : /MIT License|Permission is hereby granted, free of charge/.test(text) ? "MIT" : file ? `see ${file} in package` : "";
      license = x.match(/<license type="expression">([^<]+)<\/license>/)?.[1] ?? (fromFile || x.match(/<licenseUrl>([^<]+)<\/licenseUrl>/)?.[1]) ?? "";
    }
    // Old packages that only point at a license URL; the URL is the MIT license.
    const urlLicenses = { "https://go.microsoft.com/fwlink/?linkid=869050": "MIT" };
    return { name, version, license: urlLicenses[license] ?? license };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// ---------- Cargo ----------
const meta = JSON.parse(
  execSync("cargo metadata --format-version 1 --filter-platform x86_64-pc-windows-msvc", { cwd: join(root, "desktop/src-tauri"), maxBuffer: 64 << 20 }).toString(),
);
const resolved = new Set(meta.resolve.nodes.map((n) => n.id));
const cargo = meta.packages
  .filter((p) => resolved.has(p.id) && !meta.workspace_members.includes(p.id))
  .map((p) => ({ name: p.name, version: p.version, license: p.license ?? "" }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

// ---------- pnpm ----------
const pnpmJson = JSON.parse(execSync("pnpm licenses list --prod --json", { cwd: join(root, "desktop"), maxBuffer: 64 << 20 }).toString());
const npm = Object.entries(pnpmJson)
  .flatMap(([license, pkgs]) => pkgs.flatMap((p) => (p.versions ?? [p.version]).map((version) => ({ name: p.name, version, license }))))
  .sort((a, b) => a.name.localeCompare(b.name));

const md = `# Third-party notices

${cfg.appName} uses the open source components listed below. This file is generated by \`scripts/gen-notices.mjs\`
from the actual dependency graphs; rerun it after changing dependencies.

## LibreHardwareMonitorLib (MPL-2.0)

The sensor service uses LibreHardwareMonitorLib, consumed unmodified from NuGet. It is licensed under the
Mozilla Public License 2.0. Source code: https://github.com/LibreHardwareMonitor/LibreHardwareMonitor
License text: https://www.mozilla.org/en-US/MPL/2.0/

## PawnIO (not redistributed)

Low-level hardware access uses the PawnIO driver (GPL-2.0, https://github.com/namazso/PawnIO.Setup). It is not bundled.
The installer offers to download and run the official signed setup from the project's GitHub releases.

## Sensor service (NuGet, runtime)

${table(nuget)}

## Desktop core (Rust crates, Windows target)

${table(cargo)}

## Desktop UI (npm, production)

${table(npm)}
`;
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), md);
console.log(`THIRD_PARTY_NOTICES.md: ${nuget.length} NuGet, ${cargo.length} crates, ${npm.length} npm packages`);
